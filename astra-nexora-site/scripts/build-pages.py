def eyebrow(text, light=False):
    cls = "section-eyebrow light" if light else "section-eyebrow"
    return f'<div class="{cls}"><span></span><span aria-hidden="true" class="star">✦</span>{text}</div>'


def breadcrumb_schema(items):
    return {
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": i, "name": name, "item": SITE + path}
            for i, (name, path) in enumerate(items, 1)
        ],
    }


