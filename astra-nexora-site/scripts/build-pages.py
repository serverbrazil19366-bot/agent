def sync_index():
    path = os.path.join(ROOT, "index.html")
    s = open(path).read()

    new_header = header("", "")
    if "<!-- BUILD:HEADER" in s:
        s = re.sub(r"<!-- BUILD:HEADER.*?<!-- /BUILD:HEADER -->", lambda m: new_header, s, flags=re.S)
    else:
        s = re.sub(r'<header class="site-header" id="header">.*?</header>', lambda m: new_header, s, flags=re.S)

    new_footer = footer("", "")
    if "<!-- BUILD:FOOTER" in s:
        s = re.sub(r"<!-- BUILD:FOOTER.*?<!-- /BUILD:FOOTER -->", lambda m: new_footer, s, flags=re.S)
    else:
        s = re.sub(r'<footer class="footer">.*?</footer>', lambda m: new_footer, s, flags=re.S)

    # Service rows on the homepage link to their pages
    rows = re.findall(r'<li class="svc-row reveal">.*?</li>\n(?=<li class="svc-row|</ol>)', s, flags=re.S)
    for row, svc in zip(rows, SERVICES):
        fixed = re.sub(r'<a class="svc-link" href="[^"]*">', f'<a class="svc-link" href="services/{svc["slug"]}.html">', row)
        fixed = re.sub(r'<span class="svc-link-text">[^<]*</span>', f'<span class="svc-link-text">Explore {esc(svc["nav"])}</span>', fixed)
        s = s.replace(row, fixed)

    # Concept project cards link to their pages
    for pr in PROJECTS:
        pattern = (r'(<h3>' + re.escape(esc(pr["title"])) + r'</h3>\n<p>[^<]*</p>\n<ul aria-label="Scope" class="project-tags">.*?</ul>)'
                   r'(\n<a class="project-cta"[^>]*>.*?</a>)?')
        link = f'\n<a class="project-cta project-cta-light" href="projects/{pr["slug"]}.html">View project <span aria-hidden="true">↗</span></a>'
        s = re.sub(pattern, lambda m: m.group(1) + link, s, count=1, flags=re.S)

    open(path, "w").write(s)


def main():
    os.makedirs(os.path.join(ROOT, "services"), exist_ok=True)
    os.makedirs(os.path.join(ROOT, "projects"), exist_ok=True)
    for i, s in enumerate(SERVICES, 1):
        with open(os.path.join(ROOT, "services", f"{s['slug']}.html"), "w") as f:
            f.write(service_page(s, i))
    for i, pr in enumerate(PROJECTS, 1):
        with open(os.path.join(ROOT, "projects", f"{pr['slug']}.html"), "w") as f:
            f.write(project_page(pr, i))
    sync_index()
    print(f"Built {len(SERVICES)} service pages, {len(PROJECTS)} project pages; synced index.html")


if __name__ == "__main__":
    main()
