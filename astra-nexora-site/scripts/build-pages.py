def esc(text):
    """Escape plain text for HTML (content strings may contain '&')."""
    return html.escape(text, quote=False)


def img(base, alt, sizes, prefix, cls="", eager=False):
    w, h = DIMS[base]
    srcset = ", ".join([
        f"{prefix}assets/stock/{base}-w800.webp 800w",
        f"{prefix}assets/stock/{base}-w1200.webp 1200w",
        f"{prefix}assets/stock/{base}-w2000.webp {w}w",
    ])
    loading = 'fetchpriority="high"' if eager else 'loading="lazy"'
    c = f' class="{cls}"' if cls else ""
    return (f'<img alt="{esc(alt)}"{c} decoding="async" height="{h}" {loading} sizes="{sizes}" '
            f'src="{prefix}assets/stock/{base}-w1200.webp" srcset="{srcset}" width="{w}"/>')


